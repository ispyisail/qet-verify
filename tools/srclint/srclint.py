"""General source-level invariant checks for the QET C++/Qt source tree.

Corpus-free: unlike tools/qet-lint (which sweeps the element collection) or
tools/crosspage (which sweeps example projects), srclint's rules read the
source tree directly. Runs in seconds.

See DIAGNOSTIC-TOOLS-PLAN.md G6 for the rationale behind each rule and the
measured numbers this was calibrated against.
"""
from __future__ import annotations

import argparse
import json
import re
import sys
from dataclasses import dataclass
from pathlib import Path

from connectscan import captures_this, find_connect_calls

@dataclass(frozen=True)
class Finding:
    rule: str
    severity: str
    file: str
    line: str
    detail: str
    # What identifies this finding across source edits: never the line
    # number, which moves whenever anything above it changes. Empty means
    # "use detail".
    ident: str = ""

    def format(self) -> str:
        return f"{self.severity.upper():7} {self.rule}  {self.file}:{self.line}  {self.detail}"

    def baseline_key(self) -> str:
        return f"{self.rule}|{self.file}|{self.ident or self.detail}"


# R-C's French detector. Signals, any one is enough:
#   - a word from french_lexicon.json (words QET's French text uses and its
#     English text never does, regenerated by `qet-en-source lexicon`)
#   - an accented letter, unless the word is one English text uses (Bézier)
#   - two French function words
# French typography (a space before ":", « ») is NOT a signal: about 400 of
# QET's English strings carry it over from the French ("Size :").
# Measured on master ef795a21e, lexicon learned from the 3,075 converted
# messages only: of the 63 never-converted French messages it misses 7 -
# five read as English ("Portrait", "Format :", "8 directions") and two use
# only words it has never seen ("Vider la direction") - and flags none of
# the 3,737 English ones.
_LEXICON_PATH = Path(__file__).with_name("french_lexicon.json")
_WORD = re.compile(r"[A-Za-zÀ-ÿœ]+")
_ACCENT = re.compile(r"[À-ÿœ]")
_FRENCH_WORDS = {"le", "la", "les", "des", "du", "une", "est", "pour", "avec", "dans",
                 "sur", "pas", "vous", "votre", "veuillez", "cette", "aux", "au", "ou"}
_lexicon_cache: dict | None = None


def _lexicon() -> dict:
    global _lexicon_cache
    if _lexicon_cache is None:
        with open(_LEXICON_PATH, encoding="utf-8") as fh:
            data = json.load(fh)
        _lexicon_cache = dict(french=set(data["french"]), english_accented=set(data["english_accented"]))
    return _lexicon_cache


def looks_french(text: str) -> bool:
    lex = _lexicon()
    words = [w.lower() for w in _WORD.findall(text.replace("&", ""))]
    if any(w in lex["french"] for w in words):
        return True
    if any(_ACCENT.search(w) and w not in lex["english_accented"] for w in words):
        return True
    return len(set(words) & _FRENCH_WORDS) >= 2


# The translatable string literals in C++: the first argument of tr(),
# QT_TR_NOOP() and QT_TRANSLATE_NOOP3-less forms, the second of translate()
# and QT_TRANSLATE_NOOP(). Adjacent literals ("a" "b") are one string.
_TR_CALL = re.compile(
    r"(?<![\w])(?:(?:\w+::)*tr|QT_TR_NOOP)\s*\("
    r"|(?<![\w])(?:(?:\w+::)*translate|QT_TRANSLATE_NOOP)\s*\(\s*(?:\"(?:[^\"\\\n]|\\.)*\"|[\w:.>-]+(?:\(\))?)\s*,"
)
_LITERALS = re.compile(r'\s*((?:"(?:[^"\\\n]|\\.)*"\s*)+)')
_ONE_LITERAL = re.compile(r'"((?:[^"\\\n]|\\.)*)"')
_UI_STRING = re.compile(r"<string(?P<attrs>[^>]*)>(?P<text>[^<]*)</string>")


def _blank_comments(text: str) -> str:
    """Replace // and /* */ comments with spaces, keeping newlines and the
    string literals, so offsets still give the right line numbers."""
    out = []
    i, n = 0, len(text)
    while i < n:
        c = text[i]
        if c == '"' or c == "'":
            j = i + 1
            while j < n and text[j] != c and text[j] != "\n":
                j += 2 if text[j] == "\\" else 1
            out.append(text[i:j + 1])
            i = j + 1
        elif text.startswith("//", i):
            j = text.find("\n", i)
            j = n if j < 0 else j
            out.append(" " * (j - i))
            i = j
        elif text.startswith("/*", i):
            j = text.find("*/", i + 2)
            j = n if j < 0 else j + 2
            out.append("".join(ch if ch == "\n" else " " for ch in text[i:j]))
            i = j
        else:
            out.append(c)
            i += 1
    return "".join(out)


def _unescape(literal: str) -> str:
    return re.sub(r"\\(.)", lambda m: {"n": "\n", "t": "\t"}.get(m.group(1), m.group(1)), literal)


def translatable_strings(path: Path, text: str | None = None) -> list[tuple[int, str]]:
    """(line, text) of every translatable string in a .cpp/.h or .ui file."""
    if text is None:
        text = path.read_text(encoding="utf-8", errors="replace")
    found: list[tuple[int, str]] = []
    if path.suffix == ".ui":
        for m in _UI_STRING.finditer(text):
            if 'notr="true"' in m.group("attrs") or not m.group("text").strip():
                continue
            from html import unescape
            found.append((text.count("\n", 0, m.start()) + 1, unescape(m.group("text"))))
        return found
    code = _blank_comments(text)
    for m in _TR_CALL.finditer(code):
        lit = _LITERALS.match(code, m.end())
        if not lit:
            continue
        value = "".join(_unescape(x) for x in _ONE_LITERAL.findall(lit.group(1)))
        if value.strip():
            found.append((code.count("\n", 0, lit.start(1)) + 1, value))
    return found


def rule_c_french_source(sources: Path) -> list[Finding]:
    """R-C: a translatable string written in French.

    English is QET's source language since PR #1390 (2026-10-08); French is
    a translation in lang/qet_fr.ts like any other. A French tr() string is
    a mistake: English users see French, and translators get French to
    translate. Reads the source tree itself, not a .ts file, so a new string
    is caught before anyone runs lupdate.
    """
    findings: list[Finding] = []
    for path in sorted(p for p in sources.rglob("*") if p.suffix in (".cpp", ".h", ".ui")):
        for line, text in translatable_strings(path):
            if not looks_french(text):
                continue
            findings.append(Finding(
                rule="R-C", severity="warning",
                file=str(path.relative_to(sources.parent)) if sources.parent != path else str(path),
                line=str(line),
                detail=f"French tr() source: {text!r}",
                ident=text,
            ))
    return findings


_IDENT = re.compile(r"^[A-Za-z_]\w*$")


def _sender_parented_to_this(sender: str, text: str) -> bool:
    """True if @p sender is a simple identifier whose construction in the
    same file passes "this" to its constructor -- QObject parenting, which
    guarantees the sender is destroyed with (or before) the receiver, so a
    context-less connect() from it can never fire into freed memory the way
    F013 does. Matches both a local `T *sender = new T(..., this, ...)` and
    a member `sender = new T(..., this, ...)` / `sender{new T(...this...)}`
    assignment anywhere in the file -- this is a textual heuristic, not a
    real ownership analysis, so it only recognises the direct, common
    pattern (new T(...this...)), not indirection through a factory or a
    setParent() call.
    """
    if not _IDENT.match(sender):
        return False
    pattern = re.compile(
        r"\b" + re.escape(sender) + r"\s*[=({]\s*new\s+\w+\s*\([^;]*\bthis\b[^;]*\)"
    )
    return bool(pattern.search(text))


def rule_b_contextless_lambda_connect(cpp_path: Path, text: str | None = None) -> list[Finding]:
    """R-B: a context-less lambda connect() capturing "this" whose sender
    is not provably owned by the receiver.

    `connect(sender, &Sig::sig, [this]{...})` -- no context object as a
    4th argument -- is owned by the SENDER, not by `this`. If `this` (the
    receiver the lambda touches) is destroyed before the sender, the
    connection survives and later fires into freed memory
    (FINDINGS.md F013, proven under ASan on a standalone model with the
    identical ownership graph as
    sources/TerminalStrip/ui/terminalstriptreedockwidget.cpp:67).

    This is a WARNING-severity heuristic, not a proof of a bug: without a
    real ownership/lifetime analysis, "is the sender guaranteed to outlive
    the receiver" can only be approximated lexically. Exclusions, checked
    against real call sites before relying on them (see srclint's README):

    - sender is `this` itself -- the object can't outlive itself.
    - sender is `ui->...` -- owned by the Ui:: struct, which is itself a
      member destroyed with the receiver.
    - sender is provably parented to `this` via `new T(..., this, ...)`
      (a local or a member) -- Qt parenting guarantees the sender's
      lifetime is bounded by the receiver's.

    Everything else is flagged, INCLUDING constructor-parameter members,
    QPointer<T> members, and singleton accessors -- exactly the cases
    DIAGNOSTIC-TOOLS-PLAN.md G6.2 calls out as real risk, because none of
    those guarantee the sender dies with the receiver.

    A connect to `&Class::destroyed` capturing `[this]` is ALWAYS flagged
    at "critical" severity regardless of the sender exclusions above --
    the signal itself means "the sender is dying right now", so even a
    parented sender reaching this point is a receiver-lifetime question,
    not a sender-lifetime one, and F013 IS exactly this shape.
    """
    if text is None:
        text = cpp_path.read_text(encoding="utf-8", errors="replace")

    findings: list[Finding] = []
    for call in find_connect_calls(text):
        if len(call.args) != 3:
            continue
        if not captures_this(call.args[2]):
            continue
        sender, signal = call.args[0], call.args[1]

        if re.search(r"::destroyed\b", signal):
            findings.append(
                Finding(
                    rule="R-B",
                    severity="critical",
                    file=str(cpp_path),
                    line=str(call.start_line),
                    detail=f"connect({sender}, {signal}, [this]...) -- context-less "
                    f"connect to a destroyed signal capturing this; verify the "
                    f"enclosing destructor disconnects it (FINDINGS.md F013 shape)",
                )
            )
            continue

        if sender == "this":
            continue
        if sender.startswith("ui->"):
            continue
        if _sender_parented_to_this(sender, text):
            continue

        findings.append(
            Finding(
                rule="R-B",
                severity="warning",
                file=str(cpp_path),
                line=str(call.start_line),
                detail=f"connect({sender}, {signal}, [this]...) -- context-less, "
                f"sender's lifetime relative to this is not provably bounded",
            )
        )
    return findings


# R-C runs by default. R-B does NOT: DIAGNOSTIC-TOOLS-PLAN.md G6.2 says it
# "ships behind --rule until its flagged set is under ~15" -- measured at
# 59 on the current tree (down from 135 raw candidates once the sender-
# safety heuristic is applied, but still well over that bar), so it stays
# opt-in via --rule R-B rather than joining the default run.
DEFAULT_RULES = ("R-C",)
ALL_RULES = ("R-B", "R-C")


def count_keys(findings: list[Finding]) -> dict[str, int]:
    counts: dict[str, int] = {}
    for f in findings:
        k = f.baseline_key()
        counts[k] = counts.get(k, 0) + 1
    return dict(sorted(counts.items()))


def compare_baseline(current: dict[str, int], baseline: dict[str, int]):
    """(new, gone): keys whose count went up, and keys whose count went down.
    Only new ones fail the gate; gone ones are printed so a rule that quietly
    stopped firing is visible, not mistaken for progress."""
    new = [(k, n, baseline.get(k, 0)) for k, n in current.items() if n > baseline.get(k, 0)]
    gone = [(k, current.get(k, 0), n) for k, n in baseline.items() if current.get(k, 0) < n]
    return new, gone


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--qet-dir",
        type=Path,
        help="a QET checkout; sets --sources to its sources/ tree",
    )
    parser.add_argument(
        "--sources",
        type=Path,
        default=Path("sources"),
        help="path to the sources/ tree (default: sources/ relative to cwd)",
    )
    parser.add_argument(
        "--rule",
        action="append",
        dest="rules",
        choices=ALL_RULES,
        help=f"run only this rule (repeatable). Default: {', '.join(DEFAULT_RULES)}. "
        f"R-B is opt-in -- see its docstring for why.",
    )
    parser.add_argument(
        "--gate",
        action="store_true",
        help="exit non-zero if any finding is reported (with --baseline: "
        "only a finding the baseline does not already count)",
    )
    parser.add_argument(
        "--baseline",
        type=Path,
        help="JSON map of finding key -> accepted count; with --gate, only "
        "findings beyond it fail. Keys are rule|file|source string (R-C) or "
        "rule|file|detail (R-B) -- no line numbers",
    )
    parser.add_argument(
        "--write-baseline",
        action="store_true",
        help="record the current findings as --baseline and exit 0",
    )
    args = parser.parse_args(argv)
    if args.write_baseline and not args.baseline:
        parser.error("--write-baseline needs --baseline FILE")
    rules = args.rules or list(DEFAULT_RULES)

    findings: list[Finding] = []

    if args.qet_dir:
        args.sources = args.qet_dir / "sources"
    if not args.sources.is_dir():
        print(f"srclint: cannot find {args.sources}", file=sys.stderr)
        return 2

    if "R-C" in rules:
        findings.extend(rule_c_french_source(args.sources))

    if "R-B" in rules:
        for cpp_path in sorted(args.sources.rglob("*.cpp")):
            findings.extend(rule_b_contextless_lambda_connect(cpp_path))

    for f in findings:
        print(f.format())
    print(f"\n{len(findings)} finding(s).")

    current = count_keys(findings)
    if args.write_baseline:
        with open(args.baseline, "w", encoding="utf-8") as fh:
            json.dump(current, fh, indent=2, sort_keys=True, ensure_ascii=False)
            fh.write("\n")
        print(f"baseline written to {args.baseline} ({len(findings)} finding(s))")
        return 0

    if args.baseline:
        if not args.baseline.is_file():
            print(f"srclint: cannot find baseline {args.baseline}", file=sys.stderr)
            return 2
        with open(args.baseline, encoding="utf-8") as fh:
            baseline = {k: int(v) for k, v in json.load(fh).items()}
        new, gone = compare_baseline(current, baseline)
        if new:
            print(f"\nNEW vs {args.baseline} ({len(new)}):")
            for k, n, was in new:
                print(f"  - {k}: now {n}, was {was}")
        else:
            print(f"\nno new findings vs {args.baseline}.")
        if gone:
            print(f"  {len(gone)} gone (fixed, or the rule stopped firing):")
            for k, n, was in gone:
                print(f"    - {k}: now {n}, was {was}")
        return 1 if (args.gate and new) else 0

    if args.gate and findings:
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
